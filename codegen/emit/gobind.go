//go:embed wordfmt/wordfmt.go
var wordfmtSrc string

// spliceGoSource strips the package clause, everything before it (the package
// comment) and the import declaration from a single-file package whose only
// permitted import is "fmt" (iface.go imports it already), returning the
// declarations to append to the bindings.
// TRLC-LINKS: REQ-SDS-157, REQ-SDS-159
func spliceGoSource(src string) (string, error) {
	_, rest, ok := strings.Cut("\n"+src, "\npackage ")
	if !ok {
		return "", fmt.Errorf("no package clause")
	}
	_, rest, ok = strings.Cut(rest, "\n")
	if !ok {
		return "", fmt.Errorf("nothing after the package clause")
	}
	rest = strings.TrimLeft(rest, "\n")
	switch {
	case strings.HasPrefix(rest, "import \"fmt\"\n"):
		rest = strings.TrimPrefix(rest, "import \"fmt\"\n")
	case strings.HasPrefix(rest, "import"):
		return "", fmt.Errorf("the spliced source may import \"fmt\" only, has %q", strings.SplitN(rest, "\n", 2)[0])
	}
	if strings.Contains(rest, "\nimport ") {
		return "", fmt.Errorf("the spliced source has a second import declaration")
	}
	return strings.TrimLeft(rest, "\n"), nil
}


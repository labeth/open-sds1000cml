// EnumValue is a named value of a field.
type EnumValue struct {
	Name  string
	Value uint16
	Desc  string
}

// Field is a named bit range of a 16-bit word.
type Field struct {
	Name  string
	Mask  uint16
	Shift uint8
	Enum  []EnumValue // named values, if any (unshifted)
	Desc  string
}

// Get extracts the field from word.
func (f Field) Get(word uint16) uint16 { return (word & f.Mask) >> f.Shift }

// Put returns word with the field replaced by v (v is masked to the field width).
func (f Field) Put(word, v uint16) uint16 { return (word &^ f.Mask) | ((v << f.Shift) & f.Mask) }

// ValueName returns the enum name of the field's value in word ("" if unnamed).
func (f Field) ValueName(word uint16) string {
	v := f.Get(word)
	for _, e := range f.Enum {
		if e.Value == v {
			return e.Name
		}
	}
	return ""
}

// Register describes one selector of the map.
type Register struct {
	Name       string
	Sel        uint16
	Since      uint16 // schema version that introduced it
	Access     Access
	Pop        bool   // pop-on-read port: every read advances the source
	Strobe     bool   // write strobe: the written word is decoded, nothing is stored
	Const      bool   // read value is the fixed ConstValue
	ConstValue uint16
	AliasOf    string // read alias of another register (shares its pop)
	Stub       bool   // not implemented by this fabric increment: reads 0, writes ignored
	Fields     []Field
	Desc       string
}

// DiagEntry describes one index (or Count consecutive indices) of the DIAG window.
type DiagEntry struct {
	Name   string
	Idx    uint16
	Count  int
	Access Access
	Stub   bool // not implemented by this fabric increment: reads 0, writes ignored
	Fields []Field
	Desc   string
}

// Opcode is one accepted payload of the opcode strobe register.
type Opcode struct {
	Name  string
	Value uint16
	Desc  string
}

// MaskSel reduces a selector to the bits the fabric decodes.
func MaskSel(sel uint16) uint16 { return sel & SelMask }

// Registers returns the register table in declaration order (a fresh copy).
func Registers() []Register { return append([]Register(nil), registers...) }

// BySel returns the register decoded at sel (after MaskSel).
func BySel(sel uint16) (Register, bool) {
	sel = MaskSel(sel)
	for _, r := range registers {
		if r.Sel == sel {
			return r, true
		}
	}
	return Register{}, false
}

// ByName returns the register called name.
func ByName(name string) (Register, bool) {
	for _, r := range registers {
		if r.Name == name {
			return r, true
		}
	}
	return Register{}, false
}

// Undecoded returns the selectors the contract keeps undecoded (read 0, writes
// ignored; the vendor arm/halt words), a fresh copy.
func Undecoded() []uint16 { return append([]uint16(nil), undecoded...) }

// IsUndecoded reports whether sel (after MaskSel) is one of them.
func IsUndecoded(sel uint16) bool {
	sel = MaskSel(sel)
	for _, u := range undecoded {
		if u == sel {
			return true
		}
	}
	return false
}

// DiagWindow returns the DIAG window table in index order (a fresh copy).
func DiagWindow() []DiagEntry { return append([]DiagEntry(nil), diagWindow...) }

// Opcodes returns the opcode table (a fresh copy).
func Opcodes() []Opcode { return append([]Opcode(nil), opcodes...) }

// CheckIdentity compares the four identity words read from a fabric against this
// interface and returns a descriptive error on the first mismatch (fabric-ID,
// then version magic, then build-ID). A nil error means the fabric is the one
// this package was generated for.
func CheckIdentity(buildLo, buildHi, version, fabric uint16) error {
	if fabric != FabricID {
		return fmt.Errorf("iface: FABRIC_ID 0x%%04x, want 0x%%04x (not the %s image)", fabric, FabricID)
	}
	if version != VersionMagic {
		return fmt.Errorf("iface: VERSION 0x%%04x, want 0x%%04x", version, VersionMagic)
	}
	if got := uint32(buildHi)<<16 | uint32(buildLo); got != BuildID {
		return fmt.Errorf("iface: build-ID 0x%%08x, want 0x%%08x (mispaired fabric/app build)", got, BuildID)
	}
	return nil
}

